"""Phase 8 response-strategy evaluation dataset (synthetic, hand-labeled).

Deterministic cases for engineering regression only — NOT clinical data.
Each case freezes classifier scores so resolve_strategy + selector can be
evaluated without re-running NLP (separate from Phase 7 classification eval).

Expected fields:
- expected_strategy: Strategy literal from response.types
- expected_intent_key / expected_emotion_key: library key that SHOULD appear
  (one may be None). Both None → semantic/fallback allowed.
- forbidden_text_substrings: reply must not contain any of these (e.g. crisis
  copy, sadness support on positive messages).
"""

